import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/\/$/, "");
const sdkRoot = join(root, "node_modules", "@opencode-ai", "sdk");
const sdkPackage = JSON.parse(read(join(sdkRoot, "package.json")));
const sdkClientPath = join(sdkRoot, "dist", "gen", "sdk.gen.d.ts");
const sdkTypesPath = join(sdkRoot, "dist", "gen", "types.gen.d.ts");
const appFiles = walk(root).filter((file) => /\.(ts|tsx)$/.test(file) && !file.includes(`${root}/node_modules/`) && !file.includes(`${root}/ios/`) && !file.includes(`${root}/android/`));
const appSource = appFiles.map((file) => `// ${relative(root, file)}\n${read(file)}`).join("\n");
const opencodeSource = read(join(root, "src", "opencode.ts"));
const chatSource = read(join(root, "src", "ChatScreen.tsx"));
const clientDecl = read(sdkClientPath);
const typesDecl = read(sdkTypesPath);

const sdkMethods = extractSdkMethods(clientDecl);
const sdkMethodCalls = setOf(appSource.matchAll(/this\.client\.([a-zA-Z][\w]*(?:\.[a-zA-Z][\w]*)*)\(/g), 1);
const wrappers = [...opencodeSource.matchAll(/^\s{2}([a-zA-Z][\w]*)\([^)]*\) \{/gm)].map((match) => match[1]).filter((name) => name !== "constructor");
const directRoutes = extractDirectRoutes(opencodeSource);
const sdkEvents = extractSdkEvents(typesDecl);
const handledEvents = setOf(appSource.matchAll(/(?:event|typed|payload)\.type\s*(?:===|!==)\s*["`]([^"`]+)["`]/g), 1);
const handledEventFilters = setOf(appSource.matchAll(/type\s*===\s*["`]([^"`]+)["`]/g), 1);
const handledEventStrings = new Set([...handledEvents, ...handledEventFilters]);
const sdkPartTypes = extractSdkPartTypes(typesDecl);
const renderedParts = setOf(chatSource.matchAll(/part\.type\s*(?:===|!==)\s*["`]([^"`]+)["`]/g), 1);
const ignoredParts = new Set(["snapshot", "step-start", "step-finish"]);
const exportedTypes = [...typesDecl.matchAll(/^export type ([A-Za-z][\w]*)\b/gm)].map((match) => match[1]);
const usedTypes = new Set(exportedTypes.filter((name) => new RegExp(`\\b${escapeRegExp(name)}\\b`).test(appSource)));
const specialTools = extractSpecialTools(chatSource);

const implementedMethods = sdkMethods.filter((method) => sdkMethodCalls.has(method.id));
const visibleSdkEvents = sdkEvents.filter((event) => eventCoverage(event.type).stored || eventCoverage(event.type).rendered || eventCoverage(event.type).ignored);
const renderedSdkParts = sdkPartTypes.filter((part) => renderedParts.has(part) || ignoredParts.has(part));
const usedExportedTypes = exportedTypes.filter((type) => usedTypes.has(type));
const runtimeOnlyEvents = [...handledEventStrings].filter((type) => !sdkEvents.some((event) => event.type === type) && type.includes("."));
const detailHeaders = ["Area", "Item", "Status", "Handler", "Notes"];

const report = [
  "# OpenRemote SDK Coverage",
  "",
  "Generated by `bun run sdk-coverage`. Do not hand-edit coverage tables; update app code or generator instead.",
  "",
  "## Summary",
  "",
  table(detailHeaders, [
    coverageRow("summary", "SDK client methods", `${implementedMethods.length}/${sdkMethods.length} (${percent(implementedMethods.length, sdkMethods.length)})`, "sdk client", "implemented wrappers calling generated SDK methods"),
    coverageRow("summary", "SDK events", `${visibleSdkEvents.length}/${sdkEvents.length} (${percent(visibleSdkEvents.length, sdkEvents.length)})`, "event stream", "stored, rendered, or intentionally ignored installed SDK events"),
    coverageRow("summary", "message parts", `${renderedSdkParts.length}/${sdkPartTypes.length} (${percent(renderedSdkParts.length, sdkPartTypes.length)})`, "transcript", "rendered or intentionally ignored part types"),
    coverageRow("summary", "exported types", `${usedExportedTypes.length}/${exportedTypes.length} (${percent(usedExportedTypes.length, exportedTypes.length)})`, "typescript", "SDK exported types referenced by app source"),
  ]),
  "",
  `SDK package: \`@opencode-ai/sdk@${sdkPackage.version}\``,
  "",
  "## App Client Wrappers",
  "",
  table(detailHeaders, wrappers.map((name) => coverageRow("wrapper", `\`${name}\``, "implemented", "app client", "OpenRemote wrapper method"))),
  "",
  "## SDK Client Methods",
  "",
  table(detailHeaders, sdkMethods.map((method) => coverageRow("method", `\`${method.id}\``, sdkMethodCalls.has(method.id) ? "implemented" : "not implemented", "sdk client", sdkMethodCalls.has(method.id) ? "called by app wrapper/source" : "no app call detected"))),
  "",
  "## Direct HTTP Routes",
  "",
  directRoutes.length ? table(detailHeaders, directRoutes.map((route) => coverageRow("route", `\`${route}\``, "direct", "http", directRouteReason(route)))) : "No direct raw HTTP routes found.",
  "",
  "## Events",
  "",
  table(detailHeaders, sdkEvents.map((event) => {
    const coverage = eventCoverage(event.type);
    return coverageRow("event", `\`${event.type}\``, eventStatus(coverage), eventHandler(event.type, coverage), `${eventNotes(event.type, coverage)}; installed SDK`);
  }).concat(runtimeOnlyEvents.sort().map((type) => {
    const coverage = eventCoverage(type);
    return coverageRow("event", `\`${type}\``, eventStatus(coverage), eventHandler(type, coverage), `${eventNotes(type, coverage)}; runtime-only`);
  }))),
  "",
  "## Message Part Types",
  "",
  table(detailHeaders, sdkPartTypes.map((part) => {
    if (ignoredParts.has(part)) return coverageRow("part", `\`${part}\``, "ignored", "transcript", "no visible mobile row needed");
    const rendered = renderedParts.has(part);
    return coverageRow("part", `\`${part}\``, rendered ? "rendered" : "not implemented", "transcript", partNotes(part));
  })),
  "",
  "## Special Tool Handling",
  "",
  specialTools.length ? table(detailHeaders, specialTools.map((tool) => coverageRow("tool", `\`${tool}\``, "rendered", toolRenderedAs(tool), toolNotes(tool)))) : "No special tool branches found.",
  "",
  "## SDK Exported Type Usage",
  "",
  table(detailHeaders, exportedTypes.map((type) => coverageRow("type", `\`${type}\``, usedTypes.has(type) ? "referenced" : "not referenced", "typescript", usedTypes.has(type) ? "used by app source" : "no app reference detected"))),
  "",
].join("\n");

writeFileSync(join(root, "SDK_COVERAGE.md"), `${report}\n`);
console.log(`Wrote SDK_COVERAGE.md for @opencode-ai/sdk@${sdkPackage.version}`);
console.log(`Methods ${implementedMethods.length}/${sdkMethods.length}, visible events ${visibleSdkEvents.length}/${sdkEvents.length}, parts ${renderedSdkParts.length}/${sdkPartTypes.length}, types ${usedExportedTypes.length}/${exportedTypes.length}`);

function read(path) {
  return readFileSync(path, "utf8");
}

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    if ([".git", "node_modules", ".expo", "dist", "build"].includes(name)) return [];
    const path = join(dir, name);
    const stats = statSync(path);
    return stats.isDirectory() ? walk(path) : [path];
  });
}

function setOf(matches, index) {
  return new Set([...matches].map((match) => match[index]));
}

function extractSdkMethods(source) {
  const owners = new Map([
    ["Global", "global"],
    ["Project", "project"],
    ["Pty", "pty"],
    ["Config", "config"],
    ["Tool", "tool"],
    ["Instance", "instance"],
    ["Path", "path"],
    ["Vcs", "vcs"],
    ["Session", "session"],
    ["Command", "command"],
    ["Oauth", "provider.oauth"],
    ["Provider", "provider"],
    ["Find", "find"],
    ["File", "file"],
    ["App", "app"],
    ["Auth", "auth"],
    ["Mcp", "mcp"],
    ["Lsp", "lsp"],
    ["Formatter", "formatter"],
    ["Control", "tui.control"],
    ["Tui", "tui"],
    ["Event", "event"],
    ["OpencodeClient", "client"],
  ]);
  let current = "";
  const methods = [];
  for (const line of source.split("\n")) {
    const classMatch = line.match(/^(?:export declare class|declare class) (\w+)/);
    if (classMatch) current = classMatch[1];
    const methodMatch = line.match(/^\s{4}([a-zA-Z][\w]*)<ThrowOnError/);
    if (!methodMatch || !owners.has(current)) continue;
    const owner = owners.get(current);
    const id = owner === "client" ? `client.${methodMatch[1]}` : `${owner}.${methodMatch[1]}`;
    methods.push({ id, owner, name: methodMatch[1] });
  }
  return uniqueBy(methods, (item) => item.id).sort((left, right) => left.id.localeCompare(right.id));
}

function extractDirectRoutes(source) {
  const routes = new Set();
  for (const match of source.matchAll(/this\.request<[^>]+>\(([^\n]+)/g)) {
    const raw = match[1];
    const templated = raw.match(/^`([^`]+)`/)?.[1];
    if (templated) {
      routes.add(templated.replace(/\$\{encodeURIComponent\(([^)]+)\)\}/g, ":$1"));
      continue;
    }
    const literal = raw.match(/^["]([^"$]+)/)?.[1];
    if (literal) routes.add(literal);
  }
  return [...routes].sort();
}

function extractSdkEvents(source) {
  return [...source.matchAll(/export type (Event\w+) = \{\n\s+type: "([^"]+)"/g)].map((match) => ({ name: match[1], type: match[2] })).sort((left, right) => left.type.localeCompare(right.type));
}

function extractSdkPartTypes(source) {
  const known = ["text", "reasoning", "file", "tool", "step-start", "step-finish", "snapshot", "patch", "agent", "retry", "compaction", "subtask"];
  return known.filter((type) => source.includes(`type: "${type}"`));
}

function extractSpecialTools(source) {
  const tools = new Set();
  for (const match of source.matchAll(/part\.tool\s*===\s*["`]([^"`]+)["`]/g)) tools.add(match[1]);
  for (const match of source.matchAll(/\/\^([a-zA-Z][\w-]*)\$\/i\.test\(part\.tool\)/g)) tools.add(match[1]);
  if (/\^todo\(write\)\?\$/.test(source)) {
    tools.add("todo");
    tools.add("todowrite");
  }
  if (/grep\|glob\|search\|find/.test(source)) {
    tools.add("grep");
    tools.add("glob");
    tools.add("search");
    tools.add("find");
  }
  return [...tools].filter(Boolean).sort();
}

function table(headers, rows) {
  const escape = (value) => String(value).replace(/\n/g, "<br>").replace(/\|/g, "\\|");
  return [
    `| ${headers.map(escape).join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.map(escape).join(" | ")} |`),
  ].join("\n");
}

function coverageRow(area, item, status, handler, notes) {
  return [area, item, status, handler, notes];
}

function percent(value, total) {
  return total ? `${Math.round((value / total) * 100)}%` : "n/a";
}

function yes(value) {
  return value ? "yes" : "no";
}

function uniqueBy(items, key) {
  const seen = new Set();
  return items.filter((item) => {
    const value = key(item);
    if (seen.has(value)) return false;
    seen.add(value);
    return true;
  });
}

function directRouteReason(route) {
  if (route.startsWith("/question")) return "question API exists in runtime but not installed SDK declarations";
  if (route.startsWith("/permission")) return "permission flow uses runtime route shape not covered by current generated client";
  if (route === "/global/health") return "health check used before full SDK client flow";
  return "direct runtime route";
}

function eventCoverage(type) {
  const handled = handledEventStrings.has(type);
  const stored = handled && (
    type === "message.updated" ||
    type === "message.removed" ||
    type === "message.part.updated" ||
    type === "message.part.removed" ||
    type === "message.part.delta" ||
    type === "permission.asked" ||
    type === "permission.replied" ||
    type === "question.asked" ||
    type === "question.replied" ||
    type === "question.rejected" ||
    type === "session.created" ||
    type === "session.updated" ||
    type === "session.deleted" ||
    type === "session.status" ||
    type === "session.idle" ||
    type.startsWith("session.next.")
  );
  const rendered = stored && (
    type.startsWith("message.") ||
    type.startsWith("permission.") ||
    type.startsWith("question.") ||
    type === "session.status" ||
    type === "session.idle" ||
    type.startsWith("session.next.")
  );
  const ignored = handled && (type === "snapshot" || type === "sync");
  return { parsed: true, stored, rendered, ignored };
}

function eventNotes(type, coverage) {
  if (coverage.rendered && type.startsWith("message.part")) return "updates visible streaming transcript state";
  if (coverage.rendered && type.startsWith("message.")) return "updates visible transcript messages";
  if (coverage.rendered && type.startsWith("permission.")) return "drives permission modal state";
  if (coverage.rendered && type.startsWith("question.")) return "drives question dialog state";
  if (coverage.rendered && type.startsWith("session.next.")) return "low-latency streaming delta rendered before final message refresh";
  if (coverage.rendered && type.startsWith("session.")) return "updates visible session busy/idle state";
  if (coverage.stored && type.startsWith("session.")) return "updates local session collection";
  if (coverage.ignored) return "intentionally ignored by app parser or renderer";
  if (handledEventStrings.has(type)) return "app branch exists but no stored/rendered state detected";
  return "parsed from SSE and available to app, no stored or rendered state";
}

function eventStatus(coverage) {
  if (coverage.rendered) return "rendered";
  if (coverage.stored) return "stored";
  if (coverage.ignored) return "ignored";
  if (coverage.parsed) return "parsed";
  return "not implemented";
}

function eventHandler(type, coverage) {
  if (type === "message.part.delta" || type.startsWith("session.next.")) return "streaming transcript";
  if (type === "message.part.updated" || type === "message.part.removed") return "message part state";
  if (type === "message.updated" || type === "message.removed") return "message list state";
  if (type.startsWith("permission.")) return coverage.rendered ? "permission modal" : "permission parsed";
  if (type.startsWith("question.")) return coverage.rendered ? "question dialog" : "question parsed";
  if (type === "session.status" || type === "session.idle") return "status state";
  if (type === "session.created" || type === "session.updated" || type === "session.deleted") return "session list state";
  if (type === "server.connected" || type === "session.compacted" || type === "session.error") return "refresh trigger";
  if (coverage.ignored) return "ignored";
  if (handledEventStrings.has(type)) return "branch only";
  return "parsed only";
}

function partNotes(part) {
  const notes = {
    text: "markdown rendered",
    reasoning: "collapsed by default; markdown title; tap expanded thought to collapse; live square spinner",
    tool: "compact tool rows plus special output blocks",
    file: "file attachment/source row",
    patch: "patch summary opens diff modal",
    agent: "compact agent row",
    subtask: "compact subtask row",
    retry: "compact error row",
    compaction: "compact compaction row",
  };
  return notes[part] ?? "no note";
}

function toolNotes(tool) {
  if (tool === "question") return "native question dialog plus compact transcript row";
  if (tool === "skill") return "hides full skill_content payload";
  if (tool === "read") return "one-line Read filename row";
  if (tool === "apply_patch") return "compact patch status plus diff modal";
  if (tool === "todo" || tool === "todowrite") return "checklist output block";
  if (tool === "grep" || tool === "glob" || tool === "search" || tool === "find") return "search glyph/title treatment";
  return "special branch or grouped matcher in ChatScreen";
}

function toolRenderedAs(tool) {
  if (tool === "question") return "compact row: Asked N questions";
  if (tool === "skill") return 'compact row: Skill "<name>"';
  if (tool === "read") return "compact row: Read <path>";
  if (tool === "apply_patch") return "compact row + patch modal";
  if (tool === "todo" || tool === "todowrite") return "checklist block";
  if (tool === "grep" || tool === "glob" || tool === "search" || tool === "find") return "search event row";
  return "custom transcript branch";
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
